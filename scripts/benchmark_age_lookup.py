import time
import random

import psycopg

from benchmark.statistics import calculate_statistics


HOST = "localhost"
PORT = 5455
DATABASE = "graphdb"
USER = "postgres"
PASSWORD = "benchmark_password"

GRAPH_NAME = "pokec"

WARMUP_ITERATIONS = 20
MEASURED_ITERATIONS = 100
LOOKUP_NODE_COUNT = 100


def connect():
    return psycopg.connect(
        host=HOST,
        port=PORT,
        dbname=DATABASE,
        user=USER,
        password=PASSWORD,
    )


def initialize_age(conn):
    with conn.cursor() as cursor:
        cursor.execute("LOAD 'age'")
        cursor.execute(
            'SET search_path = ag_catalog, "$user", public'
        )


def run_cypher(conn, query):
    """
    Execute an AGE Cypher query.

    AGE requires the graph name and query to be
    SQL literals, not PostgreSQL parameters.
    """

    with conn.cursor() as cursor:

        sql = f"""
        SELECT *
        FROM ag_catalog.cypher(
            '{GRAPH_NAME}',
            $$
            {query}
            $$
        ) AS result(value ag_catalog.agtype)
        """

        cursor.execute(sql)

        return cursor.fetchall()


def get_lookup_nodes(conn):
    """
    Get actual AGE graph IDs from the User label.

    IMPORTANT:
    pokec."User".id is an AGE graphid generated by the
    AGE bulk loader. It is NOT the original Pokec node_id.
    """

    with conn.cursor() as cursor:

        cursor.execute(
            """
            SELECT id
            FROM pokec."User"
            ORDER BY id
            LIMIT %s
            """,
            (LOOKUP_NODE_COUNT,),
        )

        rows = cursor.fetchall()

    return [
        int(row[0])
        for row in rows
    ]


def lookup_node(conn, graph_id):
    """
    Look up one node using its AGE graph ID.
    """

    query = f"""
    MATCH (u:User)
    WHERE id(u) = {graph_id}
    RETURN u
    """

    return run_cypher(
        conn,
        query
    )


def main():

    print("=" * 60)
    print("Apache AGE Point Lookup Benchmark")
    print("=" * 60)

    conn = connect()

    try:

        initialize_age(conn)

        # --------------------------------------------------
        # Connection test
        # --------------------------------------------------

        run_cypher(
            conn,
            "RETURN 1"
        )

        print(
            "✓ Apache AGE connection successful"
        )

        # --------------------------------------------------
        # Select lookup nodes
        # --------------------------------------------------

        lookup_nodes = get_lookup_nodes(
            conn
        )

        if len(lookup_nodes) != LOOKUP_NODE_COUNT:
            raise RuntimeError(
                f"Expected {LOOKUP_NODE_COUNT} "
                f"lookup nodes, "
                f"but found {len(lookup_nodes)}."
            )

        print(
            f"Selected lookup nodes: "
            f"{len(lookup_nodes)}"
        )

        # --------------------------------------------------
        # Warm-up
        # --------------------------------------------------

        print(
            f"Warm-up: "
            f"{WARMUP_ITERATIONS} iterations"
        )

        for _ in range(
            WARMUP_ITERATIONS
        ):

            graph_id = random.choice(
                lookup_nodes
            )

            rows = lookup_node(
                conn,
                graph_id
            )

            rows = list(rows)

            if not rows:
                raise RuntimeError(
                    "AGE lookup returned no result "
                    f"for graph ID {graph_id}"
                )

        # --------------------------------------------------
        # Measurement
        # --------------------------------------------------

        print(
            f"Measurement: "
            f"{MEASURED_ITERATIONS} iterations"
        )

        latencies = []

        for i in range(
            MEASURED_ITERATIONS
        ):

            graph_id = random.choice(
                lookup_nodes
            )

            start_time = time.perf_counter()

            rows = lookup_node(
                conn,
                graph_id
            )

            rows = list(rows)

            elapsed = (
                time.perf_counter()
                - start_time
            )

            if not rows:
                raise RuntimeError(
                    "AGE lookup returned no result "
                    f"for graph ID {graph_id}"
                )

            latencies.append(
                elapsed * 1000
            )

            if (i + 1) % 20 == 0:

                print(
                    f"Completed "
                    f"{i + 1}/"
                    f"{MEASURED_ITERATIONS}"
                )

        # --------------------------------------------------
        # Statistics
        # --------------------------------------------------

        stats = calculate_statistics(
            latencies
        )

        print()

        print("=" * 60)
        print("POINT LOOKUP RESULTS")
        print("=" * 60)

        print(
            f"p50 : "
            f"{stats['p50_ms']:.3f} ms"
        )

        print(
            f"p95 : "
            f"{stats['p95_ms']:.3f} ms"
        )

        print(
            f"mean: "
            f"{stats['mean_ms']:.3f} ms"
        )

        print(
            f"min : "
            f"{stats['min_ms']:.3f} ms"
        )

        print(
            f"max : "
            f"{stats['max_ms']:.3f} ms"
        )

        print("=" * 60)

    finally:
        conn.close()


if __name__ == "__main__":
    main()